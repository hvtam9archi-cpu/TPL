		private void LstPages_PreviewMouseLeftButtonDown(object sender, MouseButtonEventArgs e)
		{
			_isDragging = false;
			_dragStartItem = null;
			_collapseSelectionOnMouseUp = false;

			DependencyObject source = e.OriginalSource as DependencyObject;
			if (FindVisualAncestor<System.Windows.Controls.Primitives.ScrollBar>(source) != null)
				return;

			ListViewItem sourceContainer = FindVisualAncestor<ListViewItem>(source);
			if (sourceContainer?.Content is not PdfPageViewModel sourceItem)
				return;

			_dragStartPoint = e.GetPosition(lstPages);
			_dragStartItem = sourceItem;

			// Giữ multi-selection khi bắt đầu kéo một hàng đang được chọn. Nếu chỉ click,
			// selection sẽ được thu về hàng đó trong PreviewMouseLeftButtonUp.
			if (sourceContainer.IsSelected &&
				lstPages.SelectedItems.Count > 1 &&
				Keyboard.Modifiers == ModifierKeys.None)
			{
				_collapseSelectionOnMouseUp = true;
				sourceContainer.Focus();
				e.Handled = true;
			}
		}

		private void LstPages_PreviewMouseLeftButtonUp(object sender, MouseButtonEventArgs e)
		{
			if (_collapseSelectionOnMouseUp && !_isDragging && _dragStartItem != null)
			{
				lstPages.SelectedItems.Clear();
				lstPages.SelectedItem = _dragStartItem;
			}

			_dragStartItem = null;
			_collapseSelectionOnMouseUp = false;
		}

		private void LstPages_PreviewMouseMove(object sender, MouseEventArgs e)
		{
			if (_isDragging || _dragStartItem == null || e.LeftButton != MouseButtonState.Pressed)
				return;

			Point currentPos = e.GetPosition(lstPages);
			Vector diff = _dragStartPoint - currentPos;

			if (Math.Abs(diff.X) <= SystemParameters.MinimumHorizontalDragDistance &&
				Math.Abs(diff.Y) <= SystemParameters.MinimumVerticalDragDistance)
				return;

			if (!lstPages.SelectedItems.Contains(_dragStartItem))
			{
				lstPages.SelectedItems.Clear();
				lstPages.SelectedItem = _dragStartItem;
			}

			var selectedSet = new HashSet<PdfPageViewModel>(lstPages.SelectedItems.Cast<PdfPageViewModel>());
			var selectedItems = _pages.Where(selectedSet.Contains).ToList();
			if (selectedItems.Count == 0)
				return;

			_isDragging = true;
			_collapseSelectionOnMouseUp = false;
			try
			{
				var dragData = new DataObject(PdfPagesDataFormat, selectedItems);
				DragDrop.DoDragDrop(lstPages, dragData, DragDropEffects.Move);
			}
			finally
			{
				ClearDropIndicator();
				_isDragging = false;
				_dragStartItem = null;
			}
		}

		private void LstPages_DragOver(object sender, DragEventArgs e)
		{
			if (!e.Data.GetDataPresent(PdfPagesDataFormat) ||
				e.Data.GetData(PdfPagesDataFormat) is not List<PdfPageViewModel>)
			{
				e.Effects = DragDropEffects.None;
				ClearDropIndicator();
				e.Handled = true;
				return;
			}

			DependencyObject source = e.OriginalSource as DependencyObject;
			if (FindVisualAncestor<System.Windows.Controls.Primitives.ScrollBar>(source) != null ||
				FindVisualAncestor<GridViewColumnHeader>(source) != null)
			{
				e.Effects = DragDropEffects.None;
				ClearDropIndicator();
				e.Handled = true;
				return;
			}

			AutoScrollPageList(e.GetPosition(lstPages));

			if (TryGetDropPosition(e, out int insertIndex, out double indicatorY))
			{
				e.Effects = DragDropEffects.Move;
				ShowDropIndicator(insertIndex, indicatorY);
			}
			else
			{
				e.Effects = DragDropEffects.None;
				ClearDropIndicator();
			}

			e.Handled = true;
		}

		private bool TryGetDropPosition(DragEventArgs e, out int insertIndex, out double indicatorY)
		{
			insertIndex = -1;
			indicatorY = 0;

			ListViewItem targetContainer = FindVisualAncestor<ListViewItem>(e.OriginalSource as DependencyObject);
			if (targetContainer?.Content is PdfPageViewModel targetItem)
			{
				int targetIndex = _pages.IndexOf(targetItem);
				if (targetIndex < 0)
					return false;

				bool insertBefore = e.GetPosition(targetContainer).Y < targetContainer.ActualHeight / 2;
				Point topLeft = targetContainer.TranslatePoint(new Point(0, 0), lstPages);
				insertIndex = insertBefore ? targetIndex : targetIndex + 1;
				indicatorY = insertBefore ? topLeft.Y : topLeft.Y + targetContainer.ActualHeight;
				return true;
			}

			if (_pages.Count == 0)
				return false;

			var lastContainer = lstPages.ItemContainerGenerator.ContainerFromIndex(_pages.Count - 1) as ListViewItem;
			if (lastContainer == null)
				return false;

			Point lastTopLeft = lastContainer.TranslatePoint(new Point(0, 0), lstPages);
			double lastBottom = lastTopLeft.Y + lastContainer.ActualHeight;
			if (e.GetPosition(lstPages).Y < lastBottom)
				return false;

			insertIndex = _pages.Count;
			indicatorY = lastBottom;
			return true;
		}

		private void ShowDropIndicator(int insertIndex, double indicatorY)
		{
			_dropInsertIndex = insertIndex;
			AdornerLayer adornerLayer = AdornerLayer.GetAdornerLayer(lstPages);
			if (adornerLayer == null)
				return;

			if (_dropInsertionAdorner == null)
			{
				_dropInsertionAdorner = new DropInsertionAdorner(lstPages);
				adornerLayer.Add(_dropInsertionAdorner);
			}

			_dropInsertionAdorner.UpdatePosition(indicatorY);
		}

		private void ClearDropIndicator()
		{
			_dropInsertIndex = -1;
			if (_dropInsertionAdorner == null)
				return;

			AdornerLayer.GetAdornerLayer(lstPages)?.Remove(_dropInsertionAdorner);
			_dropInsertionAdorner = null;
		}

