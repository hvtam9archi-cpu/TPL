		protected override void OnKeyDown(KeyEventArgs e)
		{
			if (e.Key == Key.Escape && WindowState == WindowState.Maximized)
			{
				WindowState = WindowState.Normal;
				e.Handled = true;
				return;
			}

			bool controlPressed = (Keyboard.Modifiers & ModifierKeys.Control) == ModifierKeys.Control;
			bool shiftPressed = (Keyboard.Modifiers & ModifierKeys.Shift) == ModifierKeys.Shift;
			bool isEditingText = Keyboard.FocusedElement is System.Windows.Controls.Primitives.TextBoxBase;

			if (controlPressed && e.Key == Key.N)
			{
				_ = NewDocumentAsync();
				e.Handled = true;
			}
			else if (controlPressed && e.Key == Key.O)
			{
				_ = OpenDocumentAsync();
				e.Handled = true;
			}
			else if (controlPressed && shiftPressed && e.Key == Key.S)
			{
				_ = SaveDocumentAsync(saveAs: true);
				e.Handled = true;
			}
			else if (controlPressed && e.Key == Key.S)
			{
				_ = SaveDocumentAsync(saveAs: false);
				e.Handled = true;
			}
			else if (!isEditingText && controlPressed && e.Key == Key.Z)
			{
				Undo();
				e.Handled = true;
			}
			else if (!isEditingText && controlPressed && e.Key == Key.Y)
			{
				Redo();
				e.Handled = true;
			}
			else if (!isEditingText && controlPressed && e.Key == Key.A)
			{
				lstPages.SelectAll();
				e.Handled = true;
			}
			else if (!isEditingText && controlPressed && e.Key == Key.D)
			{
				DuplicateSelectedPages();
				e.Handled = true;
			}
			else if (!isEditingText && controlPressed && e.Key == Key.E)
			{
				_ = ExtractSelectedPagesAsync();
				e.Handled = true;
			}
			else if (!isEditingText && e.Key == Key.Delete)
			{
				BtnRemove_Click(this, new RoutedEventArgs());
				e.Handled = true;
			}

			if (!e.Handled) base.OnKeyDown(e);
		}

