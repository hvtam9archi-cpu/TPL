		/// <summary>Thêm danh sách file PDF vào editor (async — không block UI).</summary>
		public async Task AddPdfFilesAsync(List<string> files, bool isAutoGenerated = true)
		{
			if (files == null || files.Count == 0) return;
			try
			{
				await _pdfLoadGate.WaitAsync(_loadCancellation.Token);
			}
			catch (OperationCanceledException)
			{
				return;
			}

			try
			{
				if (_isClosing || _loadCancellation.IsCancellationRequested) return;
				if (isAutoGenerated) _autoGeneratedFiles.AddRange(files);

				System.Drawing.Color groupColor = GetNextColor();
				int currentGroupId = _groupIdCounter++;
				string sourceLabel = isAutoGenerated ? "Plot" : "File";
				bool firstAdd = _pages.Count == 0;
				bool separate = chkSeparatePdfs.IsChecked == true;
				CancellationToken cancellationToken = _loadCancellation.Token;

				// Disable UI trong lúc load
				btnAdd.IsEnabled = false;
				btnPlusPlot.IsEnabled = false;

				try
				{
					// Heavy I/O chạy trên background thread
					var loadedPages = await Task.Run(() =>
					{
						var results = new List<PdfPageViewModel>();
						foreach (string file in files)
						{
							cancellationToken.ThrowIfCancellationRequested();
							if (!File.Exists(file)) continue;
							try
							{
								using var doc = PdfReader.Open(file, PdfDocumentOpenMode.Import);

								if (separate || isAutoGenerated)
								{
									for (int i = 0; i < doc.PageCount; i++)
									{
										cancellationToken.ThrowIfCancellationRequested();
										results.Add(new PdfPageViewModel
										{
											SourceFile = file,
											PageIndex = i,
											GroupColor = groupColor,
											GroupId = currentGroupId,
											SourceLabel = sourceLabel,
											DisplayName = isAutoGenerated
												? Path.GetFileName(file)
												: string.Format(L10n.T("page_name"), Path.GetFileName(file), i + 1)
										});
									}
								}
								else
								{
									results.Add(new PdfPageViewModel
									{
										SourceFile = file,
										PageIndex = -1,
										GroupColor = groupColor,
										GroupId = currentGroupId,
										SourceLabel = sourceLabel,
										DisplayName = Path.GetFileName(file)
									});
								}
							}
							catch (OperationCanceledException)
							{
								throw;
							}
							catch (Exception ex)
							{
								System.Diagnostics.Debug.WriteLine($"[PdfEditor] Error loading {file}: {ex.Message}");
							}
						}
						return results;
					}, cancellationToken);

					if (_isClosing || cancellationToken.IsCancellationRequested) return;

					// Add vào ObservableCollection trên UI thread
					foreach (var page in loadedPages)
					{
						page.SequenceNumber = _pages.Count + 1;
						_pages.Add(page);
					}

					AutoResizeSequenceColumn();

					if (firstAdd && _pages.Count > 0)
						lstPages.SelectedIndex = 0;
				}
				catch (OperationCanceledException) when (_loadCancellation.IsCancellationRequested)
				{
					// Expected when the window is closing.
				}
				catch (Exception ex)
				{
					System.Diagnostics.Debug.WriteLine($"[PdfEditor] AddPdfFiles error: {ex.Message}");
				}
				finally
				{
					if (!_isClosing)
					{
						btnAdd.IsEnabled = true;
						btnPlusPlot.IsEnabled = true;
					}
				}
			}
			finally
			{
				_pdfLoadGate.Release();
				if (_isClosing && isAutoGenerated)
				{
					foreach (string file in files)
					{
						try { if (File.Exists(file)) File.Delete(file); } catch { }
					}
				}
			}
		}

