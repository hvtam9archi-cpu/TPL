		{
			if (_isBusy || _isLoading) return;
			var selected = lstPages.SelectedItems.Cast<PdfPageViewModel>().ToList();
			if (selected.Count == 0) return;
			List<PdfPageViewModel> undoSnapshot = CapturePages();

