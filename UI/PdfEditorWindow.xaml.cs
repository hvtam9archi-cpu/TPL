		// ─── Page Selection → Preview ───────────────────────────────────────
		private async void LstPages_SelectionChanged(object sender, SelectionChangedEventArgs e)
		{
			if (_isReordering) return;
			UpdateDocumentState();
			int requestId = ++_previewRequestId;

			if (lstPages.SelectedItem is PdfPageViewModel item)
			{
				try
				{
					byte[] previewData = item.PreviewData;
					if (previewData == null || previewData.Length == 0)
					{
						string sourceFile = item.SourceFile;
						int pageIndex = item.PageIndex;
						int rotationDelta = item.RotationDelta;
						previewData = await Task.Run(() => PdfDocumentService.BuildPreviewData(
							new PdfPageReference(sourceFile, pageIndex, rotationDelta)));

						if (requestId != _previewRequestId || _isClosing || lstPages.SelectedItem != item)
							return;

						item.PreviewData = previewData;
					}

					if (requestId != _previewRequestId || _isClosing || lstPages.SelectedItem != item)
						return;

					var oldDoc = _pdfViewer.Document;
					var oldStream = _currentPreviewStream;

					var ms = new MemoryStream(previewData, writable: false);
					PdfiumViewer.PdfDocument pdfDoc;
					try
					{
						pdfDoc = PdfiumViewer.PdfDocument.Load(ms);
					}
					catch
					{
						ms.Dispose();
						throw;
					}

					_currentPreviewStream = ms;
					_pdfViewer.Document = pdfDoc;
					pdfHost.Visibility = Visibility.Visible;
					UpdateZoomControls();

					oldDoc?.Dispose();
					oldStream?.Dispose();
					txtNoPreview.Visibility = Visibility.Collapsed;
				}
				catch (Exception ex)
				{
					System.Diagnostics.Debug.WriteLine($"[PdfEditor] Preview error: {ex.Message}");
				}
			}
			else
			{
				// Không có trang nào được chọn → hiện placeholder
				pdfHost.Visibility = Visibility.Collapsed;
				txtNoPreview.Visibility = Visibility.Visible;
				UpdateZoomControls();
			}
		}

