				else
				{
					ClearPreview();
				}
			}
			finally
			{
				_isReordering = false;
				if (_pages.Count > 0)
					LstPages_SelectionChanged(lstPages, null);
			}

			PushUndoSnapshot(undoSnapshot);
			MarkDirty();
		}

