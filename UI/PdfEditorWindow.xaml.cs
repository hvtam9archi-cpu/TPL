		private List<PdfPageViewModel> CapturePages() =>
			_pages.Select(ClonePage).ToList();

		private static PdfPageViewModel ClonePage(PdfPageViewModel source)
		{
			return new PdfPageViewModel
			{
				SourceFile = source.SourceFile,
				PageIndex = source.PageIndex,
				RotationDelta = source.RotationDelta,
				GroupColor = source.GroupColor,
				DisplayName = source.DisplayName,
				PreviewData = source.PreviewData,
				SourceLabel = source.SourceLabel,
				GroupId = source.GroupId,
				SequenceNumber = source.SequenceNumber
			};
		}

		private void PushUndoSnapshot(List<PdfPageViewModel> snapshot)
		{
			if (snapshot == null) return;
			const int maximumHistoryStates = 50;
			if (_undoStack.Count >= maximumHistoryStates)
			{
				List<PdfPageViewModel>[] retainedStates = _undoStack.Take(maximumHistoryStates - 1).Reverse().ToArray();
				_undoStack.Clear();
				foreach (List<PdfPageViewModel> retainedState in retainedStates)
					_undoStack.Push(retainedState);
			}

			_undoStack.Push(snapshot);
			_redoStack.Clear();
			UpdateDocumentState();
		}

		private void Undo()
		{
			if (_undoStack.Count == 0 || _isBusy || _isLoading) return;
			_redoStack.Push(CapturePages());
			RestorePages(_undoStack.Pop());
			MarkDirty();
		}

		private void Redo()
		{
			if (_redoStack.Count == 0 || _isBusy || _isLoading) return;
			_undoStack.Push(CapturePages());
			RestorePages(_redoStack.Pop());
			MarkDirty();
		}

		private void RestorePages(IReadOnlyList<PdfPageViewModel> pages)
		{
			_isReordering = true;
			try
			{
				ClearPreview();
				_pages.Clear();
				foreach (PdfPageViewModel page in pages)
					_pages.Add(ClonePage(page));
				RefreshSequenceNumbers();
				if (_pages.Count > 0) lstPages.SelectedIndex = 0;
			}
			finally
			{
				_isReordering = false;
				if (_pages.Count > 0) LstPages_SelectionChanged(lstPages, null);
				UpdateDocumentState();
			}
		}

		private void MarkDirty()
		{
			_isDirty = true;
			UpdateDocumentState();
		}

		private void UpdateDocumentState()
		{
			if (txtTitle == null) return;
			if (_isDashboardVisible)
			{
				txtTitle.Text = "TPL PDF Editor";
				return;
			}
			if (_isSpecializedToolVisible)
			{
				txtTitle.Text = $"TPL PDF Editor - {_activeToolName}";
				return;
			}

			string documentName = !string.IsNullOrEmpty(_currentFilePath)
				? Path.GetFileName(_currentFilePath)
				: string.IsNullOrWhiteSpace(txtFileName?.Text) ? "Untitled" : txtFileName.Text;
			txtTitle.Text = $"TPL PDF Editor - {_activeToolName} - {documentName}{(_isDirty ? " *" : string.Empty)}";

			int selectedCount = lstPages?.SelectedItems.Count ?? 0;
			if (txtDocumentStatus != null)
			{
				string selectionText = selectedCount > 0 ? $" - {selectedCount} selected" : string.Empty;
				string fileText = !string.IsNullOrEmpty(_currentFilePath) ? $" - {_currentFilePath}" : string.Empty;
				txtDocumentStatus.Text = $"{_pages.Count} pages{selectionText}{fileText}";
			}

			bool canInteract = !_isBusy && !_isLoading;
			if (btnUndo != null) btnUndo.IsEnabled = canInteract && _undoStack.Count > 0;
			if (btnRedo != null) btnRedo.IsEnabled = canInteract && _redoStack.Count > 0;
			if (btnSaveCommand != null) btnSaveCommand.IsEnabled = canInteract && _pages.Count > 0;
			if (btnSaveAs != null) btnSaveAs.IsEnabled = canInteract && _pages.Count > 0;
			if (btnSave != null) btnSave.IsEnabled = canInteract && _pages.Count > 0;
			if (btnExtract != null) btnExtract.IsEnabled = canInteract && selectedCount > 0;
			if (btnDuplicate != null) btnDuplicate.IsEnabled = canInteract && selectedCount > 0;
			if (btnRotateLeft != null) btnRotateLeft.IsEnabled = canInteract && selectedCount > 0;
			if (btnRotateRight != null) btnRotateRight.IsEnabled = canInteract && selectedCount > 0;
			if (btnRemove != null) btnRemove.IsEnabled = canInteract && selectedCount > 0;
			if (btnUp != null) btnUp.IsEnabled = canInteract && selectedCount > 0;
			if (btnDown != null) btnDown.IsEnabled = canInteract && selectedCount > 0;
			if (btnRotate != null) btnRotate.IsEnabled = canInteract && selectedCount > 0;
			if (btnAdd != null) btnAdd.IsEnabled = canInteract;
			if (btnOpen != null) btnOpen.IsEnabled = canInteract;
			if (btnNew != null) btnNew.IsEnabled = canInteract;
			if (btnHome != null) btnHome.IsEnabled = canInteract;
		}

		private void ClearPreview()
		{
			_previewRequestId++;
			IPdfDocument oldDocument = _pdfViewer.Document;
			_pdfViewer.Document = null;
			oldDocument?.Dispose();
			_currentPreviewStream?.Dispose();
			_currentPreviewStream = null;
			pdfHost.Visibility = Visibility.Collapsed;
			txtNoPreview.Visibility = Visibility.Visible;
			UpdateZoomControls();
		}

