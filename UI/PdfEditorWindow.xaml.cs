		private async Task NewDocumentAsync()
		{
			if (_isLoading || _isBusy) return;
			if (!await ConfirmDiscardChangesAsync()) return;
			ResetDocument(deleteOwnedSourceFiles: true);
			txtFileName.Text = string.Empty;
			ShowToolsDashboard();
		}

		private async Task<bool> OpenDocumentAsync()
		{
			if (_isLoading || _isBusy) return false;
			var dialog = new Microsoft.Win32.OpenFileDialog
			{
				Filter = "PDF Files|*.pdf",
				Multiselect = false,
				Title = "Open PDF"
			};
			if (dialog.ShowDialog() != true) return false;
			if (!await ConfirmDiscardChangesAsync()) return false;

			ResetDocument(deleteOwnedSourceFiles: true);
			string filePath = Path.GetFullPath(dialog.FileName);
			txtFileName.Text = Path.GetFileNameWithoutExtension(filePath);
			await AddPdfFilesAsync(new[] { filePath }, isAutoGenerated: false, trackHistory: false);
			if (_pages.Count == 0)
			{
				MessageBox.Show(
					"The selected PDF could not be opened.",
					"TPL PDF Editor",
					MessageBoxButton.OK,
					MessageBoxImage.Error);
				ShowToolsDashboard();
				return false;
			}

			_currentFilePath = filePath;
			_isDirty = false;
			_undoStack.Clear();
			_redoStack.Clear();
			ShowEditorWorkspace("Edit PDF");
			return true;
		}

		private async Task<bool> ConfirmDiscardChangesAsync()
		{
			if (!_isDirty || _pages.Count == 0) return true;

			MessageBoxResult result = MessageBox.Show(
				"Save changes to the current PDF before continuing?",
				"TPL PDF Editor",
				MessageBoxButton.YesNoCancel,
				MessageBoxImage.Warning);
			if (result == MessageBoxResult.Cancel) return false;
			if (result == MessageBoxResult.Yes)
				return await SaveDocumentAsync(saveAs: false);
			return true;
		}

		private void ResetDocument(bool deleteOwnedSourceFiles)
		{
			ClearPreview();
			_pages.Clear();
			_undoStack.Clear();
			_redoStack.Clear();
			_currentFilePath = null;
			_isDirty = false;
			_colorIndex = 0;
			_groupIdCounter = 0;
			if (deleteOwnedSourceFiles) DeleteOwnedSourceFiles();
			else _autoGeneratedFiles.Clear();
			UpdateDocumentState();
		}

		private void DeleteOwnedSourceFiles()
		{
			foreach (string file in _autoGeneratedFiles.Distinct(StringComparer.OrdinalIgnoreCase))
			{
				if (!string.Equals(Path.GetExtension(file), ".pdf", StringComparison.OrdinalIgnoreCase))
				{
					System.Diagnostics.Debug.WriteLine($"[PdfEditor] Refusing to delete a non-PDF owned path: '{file}'.");
					continue;
				}
				try
				{
					if (File.Exists(file)) File.Delete(file);
				}
				catch (IOException ex)
				{
					System.Diagnostics.Debug.WriteLine($"[PdfEditor] Could not delete temporary file '{file}': {ex.Message}");
				}
				catch (UnauthorizedAccessException ex)
				{
					System.Diagnostics.Debug.WriteLine($"[PdfEditor] Could not delete temporary file '{file}': {ex.Message}");
				}
			}
			_autoGeneratedFiles.Clear();
		}

		private async Task<bool> SaveDocumentAsync(bool saveAs)
		{
			if (_pages.Count == 0 || _isBusy || _isLoading) return false;

			string savePath = !saveAs ? _currentFilePath : null;
			if (string.IsNullOrEmpty(savePath))
			{
				var dialog = new Microsoft.Win32.SaveFileDialog
				{
					Filter = "PDF File|*.pdf",
					Title = L10n.T("dlg_save_pdf"),
					FileName = string.IsNullOrWhiteSpace(txtFileName.Text) ? "document.pdf" : txtFileName.Text,
					AddExtension = true,
					DefaultExt = ".pdf"
				};
				if (dialog.ShowDialog() != true) return false;
				savePath = dialog.FileName;
			}

			List<PdfPageReference> pages = _pages.Select(ToPageReference).ToList();
			if (!await SavePageReferencesAsync(pages, savePath, "Saving PDF...")) return false;

			_currentFilePath = Path.GetFullPath(savePath);
			txtFileName.Text = Path.GetFileNameWithoutExtension(_currentFilePath);
			_autoGeneratedFiles.RemoveAll(file =>
				string.Equals(Path.GetFullPath(file), _currentFilePath, StringComparison.OrdinalIgnoreCase));
			try
			{
				await RebaseToSavedDocumentAsync(_currentFilePath);
			}
			catch (Exception ex)
			{
				MessageBox.Show(
					"The PDF was saved, but the editor could not reload it.\n\n" + ex.Message,
					"TPL PDF Editor",
					MessageBoxButton.OK,
					MessageBoxImage.Warning);
				MarkDirty();
				return false;
			}
			_undoStack.Clear();
			_redoStack.Clear();
			_isDirty = false;
			UpdateDocumentState();
			return true;
		}

		private async Task RebaseToSavedDocumentAsync(string savedFilePath)
		{
			int pageCount = await Task.Run(() => PdfDocumentService.GetPageCount(savedFilePath));
			System.Drawing.Color groupColor = _pages.Count > 0 ? _pages[0].GroupColor : GetNextColor();
			int groupId = _groupIdCounter++;

			_isReordering = true;
			try
			{
				ClearPreview();
				_pages.Clear();
				for (int pageIndex = 0; pageIndex < pageCount; pageIndex++)
				{
					_pages.Add(new PdfPageViewModel
					{
						SourceFile = savedFilePath,
						PageIndex = pageIndex,
						RotationDelta = 0,
						GroupColor = groupColor,
						GroupId = groupId,
						SourceLabel = "File",
						DisplayName = string.Format(L10n.T("page_name"), Path.GetFileName(savedFilePath), pageIndex + 1),
						SequenceNumber = pageIndex + 1
					});
				}
				RefreshSequenceNumbers();
				if (_pages.Count > 0) lstPages.SelectedIndex = 0;
			}
			finally
			{
				_isReordering = false;
				if (_pages.Count > 0) LstPages_SelectionChanged(lstPages, null);
			}
		}

		private async Task ExtractSelectedPagesAsync()
		{
			var selectedPages = new HashSet<PdfPageViewModel>(lstPages.SelectedItems.Cast<PdfPageViewModel>());
			if (selectedPages.Count == 0 || _isBusy || _isLoading) return;

			string baseName = string.IsNullOrWhiteSpace(txtFileName.Text) ? "document" : txtFileName.Text;
			var dialog = new Microsoft.Win32.SaveFileDialog
			{
				Filter = "PDF File|*.pdf",
				Title = "Extract selected pages",
				FileName = baseName + "_selected.pdf",
				AddExtension = true,
				DefaultExt = ".pdf"
			};
			if (dialog.ShowDialog() != true) return;

			List<PdfPageReference> pages = _pages
				.Where(selectedPages.Contains)
				.Select(ToPageReference)
				.ToList();
			await SavePageReferencesAsync(pages, dialog.FileName, "Extracting pages...");
		}

		private async Task<bool> SavePageReferencesAsync(
			IReadOnlyList<PdfPageReference> pages,
			string outputPath,
			string progressLabel)
		{
			SetBusy(true);
			pnlProgress.Visibility = Visibility.Visible;
			pnlProgress.Value = 0;
			pnlProgress.Label = progressLabel;
			pnlProgress.Percent = "0%";

			try
			{
				await Task.Run(() => PdfDocumentService.Save(
					pages,
					outputPath,
					(current, total) =>
					{
						int percent = (int)Math.Round(current * 100d / total);
						Dispatcher.InvokeAsync(() =>
						{
							pnlProgress.Value = percent;
							pnlProgress.Percent = $"{percent}%";
							pnlProgress.Label = $"{progressLabel} {current} / {total}";
						});
					},
					CancellationToken.None));

				pnlProgress.Value = 100;
				pnlProgress.Percent = "100%";
				pnlProgress.Label = L10n.T("msg_save_success");
				return true;
			}
			catch (Exception ex)
			{
				MessageBox.Show(
					string.Format(L10n.T("msg_save_error"), ex.Message),
					L10n.T("err_title"),
					MessageBoxButton.OK,
					MessageBoxImage.Error);
				return false;
			}
			finally
			{
				SetBusy(false);
				var timer = new System.Windows.Threading.DispatcherTimer { Interval = TimeSpan.FromSeconds(2) };
				timer.Tick += (timerSender, timerArgs) =>
				{
					pnlProgress.Visibility = Visibility.Collapsed;
					timer.Stop();
				};
				timer.Start();
			}
		}

