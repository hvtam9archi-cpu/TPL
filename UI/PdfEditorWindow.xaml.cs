		private void DuplicateSelectedPages()
		{
			var selectedItems = new HashSet<PdfPageViewModel>(lstPages.SelectedItems.Cast<PdfPageViewModel>());
			if (selectedItems.Count == 0 || _isBusy || _isLoading) return;

			List<PdfPageViewModel> undoSnapshot = CapturePages();
			var duplicates = new List<PdfPageViewModel>();
			foreach (PdfPageViewModel item in _pages.Where(selectedItems.Contains).ToList())
			{
				int sourceIndex = _pages.IndexOf(item);
				PdfPageViewModel duplicate = ClonePage(item);
				_pages.Insert(sourceIndex + 1, duplicate);
				duplicates.Add(duplicate);
			}

			RefreshSequenceNumbers();
			lstPages.SelectedItems.Clear();
			foreach (PdfPageViewModel duplicate in duplicates)
				lstPages.SelectedItems.Add(duplicate);
			PushUndoSnapshot(undoSnapshot);
			MarkDirty();
		}

		private void RotateSelectedPages(int rotationDelta)
		{
			List<PdfPageViewModel> selected = lstPages.SelectedItems.Cast<PdfPageViewModel>().ToList();
			if (selected.Count == 0 || _isBusy || _isLoading) return;

			List<PdfPageViewModel> undoSnapshot = CapturePages();
			foreach (PdfPageViewModel item in selected)
			{
				int rotation = (item.RotationDelta + rotationDelta) % 360;
				if (rotation < 0) rotation += 360;
				item.RotationDelta = rotation;
				item.PreviewData = null;
			}

			PushUndoSnapshot(undoSnapshot);
			MarkDirty();
			LstPages_SelectionChanged(lstPages, null);
		}

