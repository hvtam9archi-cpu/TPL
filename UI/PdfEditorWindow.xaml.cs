		protected override void OnClosing(CancelEventArgs e)
		{
			base.OnClosing(e);
			if (e.Cancel) return;

			if (_isBusy || specializedToolWorkspace.IsBusy)
			{
				e.Cancel = true;
				MessageBox.Show(
					"Please wait for the current PDF operation to finish.",
					"TPL PDF Editor",
					MessageBoxButton.OK,
					MessageBoxImage.Information);
				return;
			}

			if (!_forceClose && _isDirty && _pages.Count > 0)
			{
				MessageBoxResult result = MessageBox.Show(
					"Save changes before closing?",
					"TPL PDF Editor",
					MessageBoxButton.YesNoCancel,
					MessageBoxImage.Warning);
				if (result == MessageBoxResult.Cancel)
				{
					e.Cancel = true;
					return;
				}

				if (result == MessageBoxResult.Yes)
				{
					e.Cancel = true;
					Dispatcher.BeginInvoke(new Action(async () =>
					{
						if (await SaveDocumentAsync(saveAs: false))
						{
							_forceClose = true;
							Close();
						}
					}));
					return;
				}
			}

			_isClosing = true;
			ClearDropIndicator();
			_previewRequestId++;
			_loadCancellation.Cancel();
		}

		protected override void OnClosed(EventArgs e)
		{
			specializedToolWorkspace.Dispose();

			// Cleanup PDF viewer
			try
			{
				if (_hwndSource != null)
				{
					_hwndSource.RemoveHook(HwndHook);
					_hwndSource = null;
				}
				_pdfViewer.Renderer.HandleCreated -= PdfRenderer_HandleCreated;
				_pdfViewer.Renderer.ZoomChanged -= PdfRenderer_ZoomChanged;
				var oldDoc = _pdfViewer?.Document;
				if (_pdfViewer != null) _pdfViewer.Document = null;
				oldDoc?.Dispose();
				_currentPreviewStream?.Dispose();
				_currentPreviewStream = null;
			}
			catch (Exception ex)
			{
				System.Diagnostics.Debug.WriteLine($"[PdfEditor] Preview cleanup error: {ex.Message}");
			}

			DeleteOwnedSourceFiles();
			_colorIndex = 0;
			_groupIdCounter = 0;
			_pages.Clear();
			_instance = null;

			base.OnClosed(e);
		}

