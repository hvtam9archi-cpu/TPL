		private void AutoScrollPageList(Point pointerPosition)
		{
			bool scrollUp = pointerPosition.Y < AutoScrollBoundary;
			bool scrollDown = pointerPosition.Y > lstPages.ActualHeight - AutoScrollBoundary;
			if (!scrollUp && !scrollDown)
				return;

			DateTime now = DateTime.UtcNow;
			if (now - _lastAutoScrollUtc < AutoScrollInterval)
				return;

			_pageListScrollViewer ??= FindVisualDescendant<ScrollViewer>(lstPages);
			if (_pageListScrollViewer == null)
				return;

			if (scrollUp)
				_pageListScrollViewer.LineUp();
			else
				_pageListScrollViewer.LineDown();

			_lastAutoScrollUtc = now;
		}

		private async void LstPages_Drop(object sender, DragEventArgs e)
		{
			if (TryGetDroppedPdfFiles(e.Data, out List<string> pdfFiles))
			{
				ClearDropIndicator();
				e.Handled = true;
				await AddPdfFilesAsync(pdfFiles, isAutoGenerated: false);
				return;
			}

			int requestedInsertIndex = _dropInsertIndex;
			ClearDropIndicator();
			e.Handled = true;

			if (requestedInsertIndex < 0 ||
				!e.Data.GetDataPresent(PdfPagesDataFormat) ||
				e.Data.GetData(PdfPagesDataFormat) is not List<PdfPageViewModel> droppedItems ||
				droppedItems.Count == 0)
				return;

			var currentItems = new HashSet<PdfPageViewModel>(_pages);
			var droppedSet = new HashSet<PdfPageViewModel>(droppedItems.Where(currentItems.Contains));
			var orderedDroppedItems = _pages.Where(droppedSet.Contains).ToList();
			if (orderedDroppedItems.Count == 0)
				return;

			requestedInsertIndex = Math.Max(0, Math.Min(requestedInsertIndex, _pages.Count));
			int removedBeforeInsert = _pages.Take(requestedInsertIndex).Count(droppedSet.Contains);
			int dropIndex = requestedInsertIndex - removedBeforeInsert;

			var reorderedItems = _pages.Where(item => !droppedSet.Contains(item)).ToList();
			dropIndex = Math.Max(0, Math.Min(dropIndex, reorderedItems.Count));
			reorderedItems.InsertRange(dropIndex, orderedDroppedItems);

			if (_pages.SequenceEqual(reorderedItems))
				return;
			List<PdfPageViewModel> undoSnapshot = CapturePages();

			_isReordering = true;
			try
			{
				foreach (var item in orderedDroppedItems)
					_pages.Remove(item);

				for (int i = 0; i < orderedDroppedItems.Count; i++)
					_pages.Insert(dropIndex + i, orderedDroppedItems[i]);

				RefreshSequenceNumbers();

				lstPages.SelectedItems.Clear();
				foreach (var item in orderedDroppedItems)
					lstPages.SelectedItems.Add(item);

				lstPages.ScrollIntoView(orderedDroppedItems[0]);
			}
			finally
			{
				_isReordering = false;
				LstPages_SelectionChanged(lstPages, null);
			}

			PushUndoSnapshot(undoSnapshot);
			MarkDirty();
		}

		private static T FindVisualAncestor<T>(DependencyObject element) where T : DependencyObject
		{
			while (element != null)
			{
				if (element is T match)
					return match;

				element = VisualTreeHelper.GetParent(element);
			}

			return null;
		}

		private static T FindVisualDescendant<T>(DependencyObject element) where T : DependencyObject
		{
			if (element == null)
				return null;

			int childCount = VisualTreeHelper.GetChildrenCount(element);
			for (int i = 0; i < childCount; i++)
			{
				DependencyObject child = VisualTreeHelper.GetChild(element, i);
				if (child is T match)
					return match;

				T descendant = FindVisualDescendant<T>(child);
				if (descendant != null)
					return descendant;
			}

			return null;
		}

		private sealed class DropInsertionAdorner : Adorner
		{
			private static readonly Pen IndicatorPen = CreateIndicatorPen();
			private double _indicatorY;

			public DropInsertionAdorner(UIElement adornedElement)
				: base(adornedElement)
			{
				IsHitTestVisible = false;
			}

			public void UpdatePosition(double indicatorY)
			{
				_indicatorY = indicatorY;
				InvalidateVisual();
			}

			protected override void OnRender(DrawingContext drawingContext)
			{
				double width = Math.Max(0, AdornedElement.RenderSize.Width - 12);
				double y = Math.Max(0, Math.Min(_indicatorY, AdornedElement.RenderSize.Height));
				drawingContext.DrawLine(IndicatorPen, new Point(6, y), new Point(6 + width, y));
			}

			private static Pen CreateIndicatorPen()
			{
				var brush = new SolidColorBrush(Color.FromRgb(0x60, 0xA5, 0xFA));
				brush.Freeze();

				var pen = new Pen(brush, 3)
				{
					StartLineCap = PenLineCap.Triangle,
					EndLineCap = PenLineCap.Triangle
				};
				pen.Freeze();
				return pen;
			}
		}

