		private void LstPages_PreviewMouseLeftButtonDown(object sender, MouseButtonEventArgs e)
		{
			_isDragging = false;
			_dragStartItem = null;
			_collapseSelectionOnMouseUp = false;

			DependencyObject source = e.OriginalSource as DependencyObject;
			if (FindVisualAncestor<System.Windows.Controls.Primitives.ScrollBar>(source) != null)
				return;

			ListViewItem sourceContainer = FindVisualAncestor<ListViewItem>(source);
			if (sourceContainer?.Content is not PdfPageViewModel sourceItem)
				return;

			_dragStartPoint = e.GetPosition(lstPages);
			_dragStartItem = sourceItem;

			// Giữ multi-selection khi bắt đầu kéo một hàng đang được chọn. Nếu chỉ click,
			// selection sẽ được thu về hàng đó trong PreviewMouseLeftButtonUp.
			if (sourceContainer.IsSelected &&
				lstPages.SelectedItems.Count > 1 &&
				Keyboard.Modifiers == ModifierKeys.None)
			{
				_collapseSelectionOnMouseUp = true;
				sourceContainer.Focus();
				e.Handled = true;
			}
		}

		private void LstPages_PreviewMouseLeftButtonUp(object sender, MouseButtonEventArgs e)
		{
			if (_collapseSelectionOnMouseUp && !_isDragging && _dragStartItem != null)
			{
				lstPages.SelectedItems.Clear();
				lstPages.SelectedItem = _dragStartItem;
			}

			_dragStartItem = null;
			_collapseSelectionOnMouseUp = false;
		}

		private void LstPages_PreviewMouseMove(object sender, MouseEventArgs e)
		{
			if (_isBusy || _isLoading) return;
			if (_isDragging || _dragStartItem == null || e.LeftButton != MouseButtonState.Pressed)
				return;

			Point currentPos = e.GetPosition(lstPages);
			Vector diff = _dragStartPoint - currentPos;

			if (Math.Abs(diff.X) <= SystemParameters.MinimumHorizontalDragDistance &&
				Math.Abs(diff.Y) <= SystemParameters.MinimumVerticalDragDistance)
				return;

			if (!lstPages.SelectedItems.Contains(_dragStartItem))
			{
				lstPages.SelectedItems.Clear();
				lstPages.SelectedItem = _dragStartItem;
			}

			var selectedSet = new HashSet<PdfPageViewModel>(lstPages.SelectedItems.Cast<PdfPageViewModel>());
			var selectedItems = _pages.Where(selectedSet.Contains).ToList();
			if (selectedItems.Count == 0)
				return;

			_isDragging = true;
			_collapseSelectionOnMouseUp = false;
			try
			{
				var dragData = new DataObject(PdfPagesDataFormat, selectedItems);
				DragDrop.DoDragDrop(lstPages, dragData, DragDropEffects.Move);
			}
			finally
			{
				ClearDropIndicator();
				_isDragging = false;
				_dragStartItem = null;
			}
		}

