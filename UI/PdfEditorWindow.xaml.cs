		public async Task InitializeAsync(
			IReadOnlyList<string> files,
			string defaultFileName,
			bool deleteSourcesOnExit)
		{
			SetDefaultFileName(defaultFileName);
			chkSeparatePdfs.IsChecked = true;

			if (files != null && files.Count > 0)
			{
				await AddPdfFilesAsync(files, deleteSourcesOnExit, trackHistory: false);
				if (_pages.Count == 0)
					throw new InvalidDataException("None of the requested PDF files could be opened.");
				if (!deleteSourcesOnExit && files.Count == 1)
				{
					_currentFilePath = Path.GetFullPath(files[0]);
					_isDirty = false;
				}
				else
				{
					_isDirty = _pages.Count > 0;
				}

				ShowEditorWorkspace("Edit PDF");
			}
			else
			{
				ShowToolsDashboard();
			}

			UpdateDocumentState();
		}

